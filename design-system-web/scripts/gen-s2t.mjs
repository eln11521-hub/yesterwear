// Generates the Simplified → Traditional character map used to clean up place
// names from the geocoder (web: src/app/s2tMap.ts, native: Shared/S2TMap.swift).
// Source: OpenCC STCharacters (Apache-2.0), minus characters that are also
// standard in Traditional / Taiwan text or common in place names (後里 must stay
// 后里, 淀川 must stay 淀川). Run: npm run gen:s2t
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const dictPath = require.resolve("opencc-js/dict/STCharacters");
const src = readFileSync(dictPath, "utf8").replace(/^export default "/, "").replace(/";?\s*$/, "");

const KEEP = new Set([
  ..."丑于云余党准几凶占划台吁吃后咸唇岩岳峰干并床斗朴杰游涌皂秘范采里雇霉郁群痴粽辟筑熏栖庄咨厘佣伙凄瓮灶淀沄肴膻苧蒏蔂虮虱虫蝎跖涂尸",
]);

const pairs = [];
for (const entry of src.split("|")) {
  const [from, to] = entry.split(" ");
  if (!from || !to || from === to || KEEP.has(from)) continue;
  pairs.push(from + to);
}
const data = pairs.join("");

const banner = "Generated by design-system-web/scripts/gen-s2t.mjs — do not edit.";
writeFileSync(
  join(here, "../src/app/s2tMap.ts"),
  `// ${banner}\n/** Pairs of [simplified, traditional] characters, concatenated. */\nexport const S2T_PAIRS =\n  "${data}";\n`,
);
writeFileSync(
  join(here, "../../Shared/S2TMap.swift"),
  `// ${banner}\n\n/// Pairs of [simplified, traditional] characters, concatenated.\nlet s2tPairs = "${data}"\n`,
);
console.log(`s2t: ${pairs.length} characters`);
